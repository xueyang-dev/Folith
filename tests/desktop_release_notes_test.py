"""D3 release notes: the disclosures must come from measured facts.

Roadmap line 57 (release notes), line 117 (per-platform language / external-install
disclosure), line 170 (supported-system statement).  The notes are generated by
`scripts/release_notes.py`; these tests keep the required disclosures present and
make sure stale notes are detected instead of shipping quietly.
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(ROOT / "scripts"))

import release_notes  # noqa: E402

MANIFEST = ROOT / "build" / "desktop" / "release-manifest.json"
DMG_RECORD = ROOT / "build" / "desktop" / "dmg_record.json"
NOTES_DIR = ROOT / "docs" / "desktop-d3"

SAMPLE = {
    "app": {"version": "1.2.3", "build_id": "git:abc1234", "commit": "abc1234",
            "worktree_dirty": False, "packaging_backend": "pyinstaller"},
    "runtime": {"python_version": "3.11.3", "streamlit_version": "1.64.0",
                "pywebview_version": "6.2.1", "pyinstaller_version": "6.22.3"},
    "ocr": {"languages": ["ara", "chi_sim", "eng"], "licence": "Apache-2.0",
            "configs_present": True, "provenance": True, "sha256_mismatches": []},
    "artifact": {"path": "/x/Folith-1.2.3-macos-arm64.dmg", "bytes": 150936527,
                 "sha256": "deadbeef", "format": "UDZO", "verify_exit_code": 0},
    "signature": {"adhoc": True, "developer_id": False, "identifier": "dev.folith.desktop"},
    "gatekeeper": {"exit_code": 3, "detail": "rejected", "notarized": False},
    "supported_systems": {"macos_minimum": "13.0", "architecture": "arm64",
                          "windows": "BLOCKED - no Windows host"},
    "bundled_distributions": [{"name": "streamlit", "version": "1.64.0"}],
    "pinned_requirements": {"requirements.txt": ["pyinstaller==6.22.3"]},
    "checks": [{"check": "bundle_identity", "ok": True, "detail": "", "blocking": True},
               {"check": "signed_with_developer_id", "ok": None, "detail": "BLOCKED",
                "blocking": False}],
}


def test_notes_disclose_languages_signature_and_systems():
    text = release_notes.render(SAMPLE, {})
    assert "语言披露" in text
    assert "`ara`" in text and "`chi_sim`" in text and "`eng`" in text
    assert "不在本版承诺内" in text, "must not claim untested languages work out of the box"
    assert "不会静默改用 `eng`" in text
    assert "未签名" in text and "未公证" in text
    assert "BLOCKED - no Windows host" in text
    assert "13.0" in text and "arm64" in text
    assert "deadbeef" in text
    assert "LibreOffice" in text and "NOT_RUN" in text
    assert "signed_with_developer_id" in text  # blocked items are named


def test_notes_mark_the_retired_shell_and_point_at_the_qt_candidate():
    text = release_notes.render(SAMPLE, {})
    assert "已退役" in text.splitlines()[0]
    assert "docs/qt-beta/release-notes.md" in text
    assert "macOS Beta" not in text.splitlines()[0]


def test_notes_never_claim_a_signature_that_does_not_exist():
    text = release_notes.render(SAMPLE, {})
    assert "已签名" not in text.replace("未签名", "")
    assert "已公证" not in text.replace("未公证", "")


def test_check_detects_drift(tmp_path, monkeypatch):
    out = tmp_path / "notes.md"
    manifest = tmp_path / "manifest.json"
    manifest.write_text(json.dumps(SAMPLE), encoding="utf-8")
    monkeypatch.setattr(release_notes, "DEFAULT_OUT_DIR", tmp_path)
    assert release_notes.main(["--manifest", str(manifest), "--out", str(out)]) == 0
    assert release_notes.main(["--manifest", str(manifest), "--out", str(out), "--check"]) == 0

    changed = json.loads(json.dumps(SAMPLE))
    changed["app"]["version"] = "1.2.4"
    manifest.write_text(json.dumps(changed), encoding="utf-8")
    assert release_notes.main(["--manifest", str(manifest), "--out", str(out), "--check"]) == 1


@pytest.mark.skipif(not MANIFEST.is_file(), reason="no release manifest here")
def test_notes_on_disk_match_the_manifest():
    manifest = json.loads(MANIFEST.read_text(encoding="utf-8"))
    version = (manifest.get("app") or {}).get("version")
    out = NOTES_DIR / f"release-notes-{version}.md"
    assert out.is_file(), "the release notes for the built version must exist"
    assert out.read_text(encoding="utf-8") == release_notes.render(
        manifest, json.loads(DMG_RECORD.read_text(encoding="utf-8")) if DMG_RECORD.is_file() else {})


def test_notes_disclose_declared_vs_verified_systems():
    """Roadmap line 11: the release page lists only actually-verified systems."""
    from scripts import release_notes

    manifest = {
        "app": {"version": "0.5.0", "minimum_system_version": "13.0"},
        "supported_systems": {"macos_minimum": "13.0", "architecture": "arm64",
                              "windows": "BLOCKED"},
        "verified_environment": {"platform": "macOS-27.0.1-arm64", "machine": "arm64",
                                 "python": "3.11.3"},
        "checks": [],
    }
    text = release_notes.render(manifest, {})
    assert "实际验收环境" in text and "macOS-27.0.1-arm64" in text
    assert "声明的" in text and "未在 13.x 实机验证" in text
    assert "只把上述实际验收环境列为已验证系统" in text


def test_notes_disclose_the_pending_clean_machine_acceptance():
    """The D2 completion condition must be visible on the release page."""
    from scripts import release_notes

    text = release_notes.render(
        {"app": {"version": "0.5.0"}, "checks": [],
         "gatekeeper": {"exit_code": 3, "notarized": False}},
        {})
    assert "干净机器验收" in text and "未完成" in text
    assert "clean-machine-acceptance.md" in text
    # The notarization line must not dump a raw temp path.
    assert "/var/folders" not in text
