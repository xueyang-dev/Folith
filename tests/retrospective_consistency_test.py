"""Retrospective consistency suggestions (#99).

The layer under test only *prepares* suggestions from evidence the pipeline
already produced.  It must never touch the working translation, review state or
delivery gate; adoption is the existing explicit candidate transaction.  These
tests pin the guarantees:

* evidence/suggestions are additive, idempotent and restart-safe;
* human-confirmed, short/title-like, dialogue/literary and explicitly
  registered-exception segments are left alone;
* the only deterministic rewrite is a forbidden rendering replaced by the locked
  preferred rendering; nothing is generated by a model;
* a candidate materialised from a suggestion still needs an explicit adoption;
* disabling the layer keeps evidence and adopted text.
"""
from __future__ import annotations

import json
from pathlib import Path

import pytest

import core
from folith import models
from folith import retrospective as retro
from folith import translation_candidates as _cand
from folith.storage import job_repository as repo
from folith import persistence_profiler

TARGET_LANG = "简体中文"


@pytest.fixture
def temp_job_env(tmp_path: Path):
    old_out = core.OUTPUT_DIR
    core.OUTPUT_DIR = tmp_path
    repo.invalidate_cache()
    core.reset_tm_dir_cache()
    persistence_profiler.disable()
    persistence_profiler.reset()
    try:
        yield tmp_path
    finally:
        core.OUTPUT_DIR = old_out
        repo.invalidate_cache()
        core.reset_tm_dir_cache()
        persistence_profiler.disable()
        persistence_profiler.reset()


def _glossary():
    return [models.normalize_glossary_entry({
        "id": "term-violet", "source": "Violet", "target": "维奥莱特",
        "preferred": "维奥莱特", "forbidden": ["紫罗兰"],
        "behavior": "translate", "status": "locked"})]


def _pair(source, target, **extra):
    pair = {"source": source, "target": target}
    pair.update(extra)
    return pair


def _conflict(segment_id, observed="紫罗兰", entry_id="term-violet"):
    return {
        "type": "glossary", "severity": "actionable", "conflict": True,
        "entry_id": entry_id, "segment_id": segment_id,
        "target_span": observed, "source_span": "Violet",
        "summary": "术语「Violet」在同一范围内出现多种译法",
        "reason": "锁定术语「Violet」在同一范围内出现多种译法，需人工统一",
    }


def _state(pairs):
    return {"pairs": list(pairs)}


def test_evidence_becomes_a_pending_suggestion_without_touching_pairs():
    pairs = [
        _pair("The Life of Violet begins in the archive.",
              "《紫罗兰》的故事从档案馆开始。"),
        _pair("Violet asks about the missing letter.",
              "维奥莱特询问那封丢失的信。"),
    ]
    before = json.dumps(pairs, ensure_ascii=False, sort_keys=True)
    state = _state(pairs)

    counts = retro.observe_batch(state, findings=[_conflict(0)],
                                 pairs=pairs, glossary=_glossary(), batch=1)

    assert counts["evidence_added"] == 1 and counts["suggestions_added"] == 1
    assert json.dumps(pairs, ensure_ascii=False, sort_keys=True) == before, \
        "建议层不得修改正文"
    view = retro.suggestion_view(state)
    assert len(view) == 1
    item = view[0]
    assert item["segment_index"] == 0
    assert item["current_target"].startswith("《紫罗兰》")
    assert item["proposed_target"] == "《维奥莱特》的故事从档案馆开始。"
    assert item["status"] == "pending"

    # Replaying the same batch (retry / journal replay / restart) changes nothing.
    again = retro.observe_batch(state, findings=[_conflict(0)],
                                pairs=pairs, glossary=_glossary(), batch=1)
    assert again["evidence_added"] == 0 and again["suggestions_added"] == 0
    assert len(retro.suggestion_view(state)) == 1


def test_human_and_ambiguous_segments_are_protected():
    pairs = [
        # human-accepted: never "unified"
        _pair("The Life of Violet begins in the archive.",
              "《紫罗兰》的故事。", human_accepted=True),
        # short/title-like
        _pair("Violet", "紫罗兰"),
        # literary quotation
        _pair('"Violet," she said, and closed the door.',
              "「紫罗兰，」她说着关上了门。"),
        # explicit exception
        _pair("The Life of Violet begins in the archive.",
              "《紫罗兰》从这里开始。"),
    ]
    state = _state(pairs)
    state["retrospective_exceptions"] = [
        {"segment_index": 3, "kind": "title", "reason": "书名译法由译者定"}]
    counts = retro.observe_batch(
        state, findings=[_conflict(0), _conflict(1), _conflict(2), _conflict(3)],
        pairs=pairs, glossary=_glossary(), batch=2)
    assert counts["evidence_added"] == 4, "证据仍要积累，便于审计"
    assert retro.suggestion_view(state) == [], "受保护段落不得产生建议"
    assert counts["skipped"] == 4


def test_no_evidence_and_disabled_switch_keep_state():
    pairs = [_pair("The Life of Violet begins in the archive.", "《紫罗兰》的故事。")]
    state = _state(pairs)
    assert retro.observe_batch(state, findings=[], pairs=pairs,
                               glossary=_glossary())["evidence_added"] == 0

    monkeypatch_ok = True
    try:
        import os
        os.environ[retro.ENV_SWITCH] = "0"
        counts = retro.observe_batch(state, findings=[_conflict(0)],
                                     pairs=pairs, glossary=_glossary())
        assert counts["enabled"] is False
        assert state.get(retro.EVIDENCE_KEY) is None, "关闭后不再新增证据"
    finally:
        import os
        os.environ.pop(retro.ENV_SWITCH, None)

    # A per-task switch has the same effect and also preserves existing records.
    state["retrospective_suggestions_enabled"] = False
    counts = retro.observe_batch(state, findings=[_conflict(0)],
                                 pairs=pairs, glossary=_glossary())
    assert counts["enabled"] is False


def test_no_deterministic_rewrite_without_a_known_forbidden_rendering():
    """An "other" rendering is evidence-only: no guessed text is proposed."""
    pairs = [_pair("The Life of Violet begins in the archive.",
                   "《Violet》的故事从档案馆开始。")]
    state = _state(pairs)
    finding = _conflict(0, observed="Violet")
    counts = retro.observe_batch(state, findings=[finding], pairs=pairs,
                                 glossary=_glossary(), batch=3)
    assert counts["evidence_added"] == 1
    assert retro.suggestion_view(state) == [], "不能凭空猜测译法"
    assert counts["skipped"] == 1


