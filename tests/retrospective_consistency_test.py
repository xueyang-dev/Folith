# integration: a real translation run accumulates evidence, still no model call
# --------------------------------------------------------------------------
def _run_with_forbidden_term(job_id, temp_job_env: Path):
    glossary = _glossary()
    sources = [
        "The Life of Violet begins in the northern archive.",
        "Violet asks about the missing letter again.",
        "Nobody tells Violet what happened in the archive.",
    ]
    state = core.new_job_state("violet.docx")
    state["paras"] = sources
    core.save_job_state(job_id, state)

    calls = []

    def llm(provider, api_key, model, system_prompt, user_prompt, **kwargs):
        calls.append(user_prompt)
        # Segment 0 and 2 use the forbidden rendering, segment 1 the preferred
        # one: the deterministic conflict detector reports both usages.
        targets = [
            "《紫罗兰》的故事从北方档案馆开始。",
            "维奥莱特再次询问那封丢失的信。",
            "没有人告诉紫罗兰档案馆里发生了什么。",
        ]
        numbered = [line for line in user_prompt.splitlines() if line.strip()[:1].isdigit()]
        return json.dumps(targets[:len(numbered)], ensure_ascii=False)

    original = core.call_llm
    core.call_llm = llm
    try:
        core.translate_stage(
            state, job_id, glossary=glossary, provider="DeepSeek", api_key="k",
            model="m", target_lang=TARGET_LANG, style_rules="",
            enable_review=False, use_tm=False, batch_size=3,
            translation_concurrency=1)
    finally:
        core.call_llm = original
    return core.load_job_state(job_id), calls


def test_translation_run_accumulates_evidence_with_guarded_suggestions(
        temp_job_env: Path):
    state, calls = _run_with_forbidden_term("retro-run", temp_job_env)
    assert state["retrospective_stats"]["evidence_added"] >= 1
    evidence = state.get("retrospective_evidence") or []
    assert {item["segment_index"] for item in evidence} == {0, 2}
    assert all(item["preferred_target"] == "维奥莱特" for item in evidence)
    suggestions = core.retrospective_suggestions(state=state)
    assert [item["segment_index"] for item in suggestions] == [0, 2]
    # The run itself did not change the working translation to the suggestion.
    assert state["pairs"][0]["target"].startswith("《紫罗兰》")
    # The suggestion layer adds no model call of its own.
    assert len(calls) >= 1


def test_materialize_then_explicit_adoption_is_the_only_text_change(
        temp_job_env: Path):
    job_id = "retro-adopt"
    state, _calls = _run_with_forbidden_term(job_id, temp_job_env)
    suggestion = core.retrospective_suggestions(state=state)[0]

    result = core.materialize_retrospective_suggestion(
        job_id, suggestion["suggestion_id"], actor="tester")
    assert result["candidate"] is not None, result
    mid = core.load_job_state(job_id)
    assert mid["pairs"][0]["target"].startswith("《紫罗兰》"), \
        "物化只是候选，不得写正文"
    candidate = result["candidate"]
    assert candidate["origin"] == _cand.ORIGIN_RETROSPECTIVE

    adopted = core.adopt_translation_candidate(
        job_id, candidate["candidate_id"], actor="tester")
    assert adopted.get("committed") is True
    final = core.load_job_state(job_id)
    assert final["pairs"][0]["target"] == "《维奥莱特》的故事从北方档案馆开始。"


def test_dismiss_keeps_evidence_and_does_not_change_text(temp_job_env: Path):
    job_id = "retro-dismiss"
    state, _calls = _run_with_forbidden_term(job_id, temp_job_env)
    suggestion = core.retrospective_suggestions(state=state)[0]
    before = state["pairs"][0]["target"]
    core.dismiss_retrospective_suggestion(job_id, suggestion["suggestion_id"],
                                          actor="tester", reason="书名译法保留")
    after = core.load_job_state(job_id)
    assert after["pairs"][0]["target"] == before
    assert after["retrospective_evidence"], "回滚/忽略不删除证据"
    record = retro.find_suggestion(after, suggestion["suggestion_id"])
    assert record["status"] == retro.STATUS_DISMISSED


def test_observation_is_pure_local_and_never_calls_a_model(monkeypatch):
    def boom(*_args, **_kwargs):
        raise AssertionError("retrospective layer must not call a model")

    monkeypatch.setattr(core, "call_llm", boom)
    pairs = [_pair("The Life of Violet begins in the archive.",
                   "《紫罗兰》的故事从档案馆开始。")]
    state = _state(pairs)
    counts = retro.observe_batch(state, findings=[_conflict(0)], pairs=pairs,
                                 glossary=_glossary(), batch=0)
    assert counts["evidence_added"] == 1 and counts["suggestions_added"] == 1


def test_complex_cast_suggestions_do_not_cross_contaminate_names():
    """A Solitude-style cast: similar renderings must stay separate terms."""
    glossary = [
        models.normalize_glossary_entry({
            "id": "term-aureliano", "source": "Aureliano",
            "target": "奥雷里亚诺", "forbidden": ["奥雷利亚诺"],
            "behavior": "translate", "status": "locked"}),
        models.normalize_glossary_entry({
            "id": "term-arcadio", "source": "Arcadio",
            "target": "阿尔卡蒂奥", "forbidden": ["阿卡迪奥"],
            "behavior": "translate", "status": "locked"}),
    ]
    pairs = [
        _pair("Aureliano Buendía remembers the ice.",
              "奥雷里亚诺·布恩迪亚想起了冰块。"),
        _pair("Aureliano Buendía remembers the ice again.",
              "奥雷利亚诺·布恩迪亚再次想起了冰块。"),
        _pair("Arcadio Buendía remembers the ice.",
              "阿尔卡蒂奥·布恩迪亚想起了冰块。"),
        _pair("Arcadio Buendía remembers the ice again.",
              "阿卡迪奥·布恩迪亚再次想起了冰块。"),
    ]
    state = _state(pairs)
    counts = retro.observe_batch(
        state,
        findings=[_conflict(1, observed="奥雷利亚诺", entry_id="term-aureliano"),
                  _conflict(3, observed="阿卡迪奥", entry_id="term-arcadio")],
        pairs=pairs, glossary=glossary, batch=0)
    assert counts["suggestions_added"] == 2
    suggestions = retro.suggestion_view(state)
    by_index = {item["segment_index"]: item for item in suggestions}
    assert by_index[1]["proposed_target"] == "奥雷里亚诺·布恩迪亚再次想起了冰块。"
    assert by_index[3]["proposed_target"] == "阿尔卡蒂奥·布恩迪亚再次想起了冰块。"
    # No suggestion touches the already-correct segments.
    assert set(by_index) == {1, 3}
